#!/usr/bin/env python3
"""部品別の熱概算(再循環を含む簡易モデル) → docs/thermal-analysis.md。数値は公開仕様+仮定。CFD/実測で置換すること。"""
import json, os
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rho, cp = 1.2, 1005.0
# 発熱(W): 出典は parts.json / 公式TDP・TGP, 内訳は仮定を明記
Q = {'CPU 9800X3D (PPT)': 162, 'GPU RTX 5060 Ti (TGP)': 180, '基板/VRM損失+RAM+SSD': 45, 'ファン/ポンプ': 16, 'PSU損失(750W中423W負荷, 効率≈91%)': 40, 'コントローラ+パネル(最大37.3W/0.9=41W)': 41}
P_tot = sum(Q.values())
fans = {'ラジエーターP12 Pro×2': 131 * 2, 'ケースファン NF-A12x25×1': 102}   # m3/h 公称
flow_nom = sum(fans.values())
out = ['# 熱解析(部品別・再循環モデル) (自動生成: tools/thermal_calc.py)', '', '**簡易モデルであり実機試験の代替ではない**。仮定: 室温25℃、ドーム内は完全混合、公称風量の実効係数を3水準で評価。CPU/GPU温度は公開レビュー値(未検証)で外挿。', '', '## 発熱内訳(W)', '| 項目 | W |', '|---|---|'] + [f'| {k} | {v} |' for k, v in Q.items()] + [f'| **合計** | **{P_tot}** |', '', '電源負荷(12V系: CPU162+GPU180+他≈100)≈440W、SF750の使用率≈59%(余裕41%)。', '']
out += ['## ドーム内空気温度(完全混合)', '排気経路を2通り評価: (A) ラジエーターが室外へ直接排気(CPU熱は内部に入らない)、(B) ラジエーター排気がドーム内に戻る(再循環, 最悪)。', '', '| 実効風量係数 | 総風量 m3/h | (A) 内部温度上昇 K | (B) 内部温度上昇 K |', '|---|---|---|---|']
for k in (0.7, 0.55, 0.4):
    V = flow_nom * k / 3600; dA = (P_tot - Q['CPU 9800X3D (PPT)']) / (rho * cp * V); dB = P_tot / (rho * cp * V)
    out.append(f'| {k} | {flow_nom*k:.0f} | {dA:.1f} | {dB:.1f} |')
out += ['', '## 部品温度の概算(係数0.55, 室温25℃)']
V = flow_nom * 0.55 / 3600; dA = (P_tot - 162) / (rho * cp * V); dB = P_tot / (rho * cp * V)
cpu_dT = 45   # 240mm AIO + 9800X3D 162W: 公開レビューの概略(室温比+40〜50K, 未検証)
gpu_dT = 40   # 2.5スロット2ファンGPU 180W: 室温比+35〜45K(未検証)
out += ['| 部品 | 室温+内部上昇 | 部品固有上昇(仮定) | 推定温度 | 上限 | 判定 |', '|---|---|---|---|---|---|']
for nm, dT, lim in (('CPU(A: 直排気)', cpu_dT, 90), ('CPU(B: 再循環)', cpu_dT, 90), ('GPU', gpu_dT, 83)):
    ti = 25 + (dB if '再循環' in nm or nm == 'GPU' else dA); t = ti + dT
    out.append(f'| {nm} | {ti:.1f} | {dT} | {t:.0f}℃ | {lim}℃ | {"余裕あり" if t < lim - 5 else "要注意" if t < lim else "超過"} |')
out += ['', '## 懸念と対策', '- 縦置きディスプレイ背面は自然対流が上向きに働くため、吸気を下側/排気を上側に偏らせると効率が上がる(v7: 均一格子+内部の仕切りで流路を作る案をCFDで評価)。', '- GPUファンはドーム側の空気を吸う → 内部温度が上がるとGPU温度が直接上がる。内部温度上昇を≤10K(B)に抑える風量を確保。', '- PSU/ポンプVRMファン/基板は局所温度を別途実測。パネル背面温度≤45℃を要確認(バックライト寿命)。', '', '## 試験計画(未実施)', '1. 熱電対(K型)8点: 吸気(格子外)、ドーム内中央、ラジエーター吸気/排気、CPU(ソフト)、GPU(ソフト)、VRM、SSD、パネル背面、外装表面。', '2. 負荷: Cinebench 30分+FurMark 30分同時。室温25±2℃。ファンRPMとSPLを同時記録。', '3. 合格: CPU<90℃, GPU<83℃, 内部上昇≤10K, パネル背面≤45℃, 外装表面≤48℃, 騒音≤38dBA。', '4. 不合格時: 格子の開口率拡大、ラジエーターを直排気にする仕切り、ケースファン増設(2基)。']
open(f'{R}/docs/thermal-analysis.md', 'w').write('\n'.join(out) + '\n'); print('\n'.join(out[8:22]))
