"""利用者/整備者向け手順書の生成器(単一源: model/*.json)。

生成物: docs/build-guide.md, docs/service-manual.md, docs/service-mechanisms.md
手で直さず、本ファイルのテンプレートか model/*.json を直して再実行する:  python3 tools/gen_manuals.py
数値は spec.json / balance.json / custom_parts.json / hardware_list.json / layout.json / cables.json と
tools/massmodel.py から取得する(テンプレートに数値を直書きしない。直書きが残る箇所は <<…>> でなく
「model/… を参照」と明記する)。未確認事項は UNVERIFIED と書き、確定扱いにしない。
"""
import json, os, re, sys
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, f'{R}/tools')
S = json.load(open(f'{R}/model/spec.json'))
B = json.load(open(f'{R}/model/balance.json'))
CP = {p['id']: p for p in json.load(open(f'{R}/model/custom_parts.json'))['parts']}
HW = json.load(open(f'{R}/model/hardware_list.json'))
LAY = json.load(open(f'{R}/model/layout.json'))
import massmodel as MM

def hw(sub):
    for h in HW:
        if sub in h['name']:
            return h
    raise KeyError(sub)

def feat(cp, key):
    for f in CP[cp]['features']:
        if key in f:
            return f
    raise KeyError((cp, key))

def torque_of(text):
    m = re.search(r'([\d.]+)\s*N·m', text)
    return m.group(1) if m else '?'

hinge, sw, neck, ds, fits, st, dome = S['hinge'], S['swivel'], S['neck'], S['dome_seal'], S['fits'], S['stand'], S['dome']
head_kg = MM.head_cg()[0]; stand_kg = MM.stand_mass()
V = {
    'head_kg': f'{head_kg:.1f}', 'stand_kg': f'{stand_kg:.1f}', 'total_kg': f'{head_kg + stand_kg:.1f}',
    'tray_kg': f"{fits['pin_tray_mass_kg']:.1f}",
    'tilt_min': f"{hinge['tilt_min_deg']:g}", 'tilt_max': f"{hinge['tilt_max_deg']:g}", 'swivel': f"{sw['range_deg']:g}",
    'ax_z': f"{hinge['axis_z_from_glass']:g}", 'ax_y': f"{hinge['axis_y']:g}",
    'fric': f"{hinge['friction_hold_Nm']:g}", 'fric_tol': f"{hinge['friction_tol_pct']:g}", 'op_N': f"{hinge['op_target_N']:g}",
    'F0': f"{B['F0_total']:g}", 'F0_each': f"{B['F0_total'] / 2:g}", 'Fmax': f"{B['F_spring_max']:g}", 'k': f"{B['k_spring']:g}",
    'bal_tol_F': f"{hinge['balance_force_tol_pct']:g}", 'bal_tol_cg': f"{hinge['balance_cg_tol_mm']:g}",
    'shim': '0.25', 'lmin': f"{B['lmin']:g}", 'lmax': f"{B['lmax']:g}", 'lfree': f"{B['free_length_min']:g}",
    'sw_hold': f"{sw['holding_torque_Nm']:g}", 'sw_stator': f"{2 * sw['stator_r']:g}", 'sw_rotor': f"{2 * sw['rotor_r']:g}",
    'sw_pcd_in': f"{sw['pcd_inner']:g}", 'sw_pcd_out': f"{sw['pcd_outer']:g}",
    'dome_t': f"{dome['total_t']:g}", 'seal_line': f"{ds['line_force_N_per_mm']:g}", 'seal_per': f"{ds['perimeter_mm']:g}",
    'seal_comp': f"{ds['comp_nom'] * 100:.0f}", 'seal_nom': f"{ds['line_force_N_per_mm'] * ds['perimeter_mm']:.0f}",
    'seal_max': f"{ds['line_force_N_per_mm'] * ds['perimeter_mm'] * (ds['comp_nom'] + ds['comp_tol']) / ds['comp_nom']:.0f}",
    'latch_n': f"{ds['latch_n']}", 'latch_hold': f"{ds['latch_hold_N']}", 'side_hooks': f"{ds['side_hooks']}", 'side_hook_hold': f"{ds['side_hook_hold_N']}",
    'foot_w': f"{st['foot_w']:g}", 'foot_d': f"{st['foot_depth']:g}", 'foot_f': f"{st['foot_front']:g}", 'foot_b': f"{st['foot_back']:g}", 'ballast': f"{st['ballast_kg']:g}",
    'shroud_skirt_r': f"{st['shroud']['skirt_r_mm']:g}", 'shroud_gap': f"{st['shroud']['skirt_gap_mm']:g}",
    'lever': f"t{neck['lever_t']:g}×幅{neck['lever_w']:g}×長{neck['lever_len']:g}", 'pad': f"{neck['pad_thick']:g}",
    'boot_lo': f"{neck['boot']['length_range_mm'][0]}", 'boot_hi': f"{neck['boot']['length_range_mm'][1]}", 'boot_n': f"{neck['boot']['convolutions']}",
    'umb': f"{CP['CP-17']['size'][0]:g}", 'umb_spare': '100',
    'pin_torque': torque_of(feat('CP-04', 'N·m')), 'hinge_torque': torque_of(hw('M6貫通')['spec']), 'restr_torque': torque_of(hw('拘束ネジ')['spec']),
    'keyhole_up': '12', 'kh_slot': f"{fits['keyhole_slot_w']:g}", 'pin_d': f"{fits['pin_shoulder_d']:g}",
    'tray_w': f"{CP['CP-06']['size'][0]:g}", 'tray_h': f"{CP['CP-06']['size'][1]:g}",
    'n_keyholes': f"{len(LAY['keyholes'])}",
    'ground_ohm': '0.1', 'sw_op': f"{sw['holding_torque_Nm'] / 0.31:.1f}",
}

def cp_table():
    rows = ['| 部品番号 | 名称 | 数量 | 材質 | 部品図 |', '|---|---|---|---|---|']
    for cid, p in CP.items():
        mat = str(p['material']).split('+')[0].split('(')[0].strip()[:42]
        rows.append(f"| {cid} | {p['name']} | {p['qty']} | {mat} | drawings/parts/{cid}.svg |")
    return '\n'.join(rows)

V['cp_table'] = cp_table()

def render(t):
    def rep(m):
        return V[m.group(1)]
    out = re.sub(r'<<(\w+)>>', rep, t)
    assert '<<' not in out
    return out.strip() + '\n'

